$bridge = @'
// lan-bridge.mjs - expose the Desktop app's own harness host on the LAN.
//
// Why: a second `dsh web` host is a different process, so it cannot open a session the
// Desktop app already holds ("error.sessionInUse"). Bridging to the Desktop host keeps
// ONE process owning every session, so the phone and the desktop share live chats.
//
// How: exactly one request per upstream connection (Connection: close unless this is a
// WebSocket upgrade). Every request head is rewritten:
//   Host / Origin -> 127.0.0.1:<desktop host port>   (the /api fence compares the two)
//   Cookie        -> any dsh-auth-* dropped, one cookie signed with the store's
//                    persistent browser-session secret appended, bound to that authority
// Requests without the gate cookie (minted by GET /e/<PIN>) never reach the host: the
// injected cookie is owner-level, so the port needs its own door.
//
// Env: DSH_BRIDGE_HOST, DSH_BRIDGE_PORT, DSH_BRIDGE_DIR, DSH_BRIDGE_PIN, DSH_CREDENTIALS
import { createServer, connect } from 'node:net'
import { readFileSync, appendFileSync } from 'node:fs'
import { join } from 'node:path'
import { createHash, createHmac } from 'node:crypto'

const listenHost = process.env.DSH_BRIDGE_HOST ?? '127.0.0.1'
const listenPort = Number(process.env.DSH_BRIDGE_PORT ?? 64602)
const dir = process.env.DSH_BRIDGE_DIR ?? '.'
const pin = process.env.DSH_BRIDGE_PIN ?? ''
const credFile = process.env.DSH_CREDENTIALS
  ?? join(process.env.USERPROFILE ?? '.', '.dsh', '.credentials.yaml')
const logFile = join(dir, 'lan-bridge.log')

if (!pin) {
  console.error('lan-bridge: DSH_BRIDGE_PIN is required')
  process.exit(2)
}

const GATE_COOKIE = 'dsh-gate'
const GATE_VALUE = createHmac('sha256', 'dsh-lan-bridge').update(pin).digest('hex').slice(0, 32)
const GATE_PATH = `/e/${pin}`

const b64u = (buf) => Buffer.from(buf).toString('base64')
  .replaceAll('+', '-').replaceAll('/', '_').replace(/=+$/u, '')

function log(text) {
  try { appendFileSync(logFile, `${new Date().toISOString()} ${text}\n`) } catch { }
}

function desktopPort() {
  try {
    const v = readFileSync(join(dir, 'desktop-host.port'), 'utf8').trim()
    return /^\d+$/.test(v) ? Number(v) : null
  } catch { return null }
}

// The signing secret lives in the credential store; it is persistent, so a cookie minted
// here keeps working across harness restarts (the launch token would not).
let secretCache = { at: 0, value: null }
function secret() {
  if (secretCache.value && Date.now() - secretCache.at < 30000) return secretCache.value
  const text = readFileSync(credFile, 'utf8')
  const at = text.indexOf('client-connection/browser-session:')
  if (at === -1) throw new Error('browser-session credential record not found')
  const m = text.slice(at, at + 600).match(/secret:\s*([A-Za-z0-9_-]{40,})/u)
  if (!m) throw new Error('browser-session secret not found')
  const value = Buffer.from(m[1].replaceAll('-', '+').replaceAll('_', '/'), 'base64')
  secretCache = { at: Date.now(), value }
  return value
}

function cookieFor(authority) {
  const name = 'dsh-auth-' + b64u(createHash('sha256').update(authority).digest())
  const now = Date.now()
  const payload = { version: 1, authority, issuedAt: now, expiresAt: now + 30 * 24 * 3600 * 1000 }
  const body = b64u(Buffer.from(JSON.stringify(payload), 'utf8'))
  const value = `v1.${body}.${b64u(createHmac('sha256', secret()).update(body).digest())}`
  return `${name}=${value}`
}

function gated(headers) {
  for (const [name, value] of headers) {
    if (name.toLowerCase() !== 'cookie') continue
    for (const part of value.split(';')) {
      const at = part.indexOf('=')
      if (at === -1) continue
      if (part.slice(0, at).trim() === GATE_COOKIE && part.slice(at + 1).trim() === GATE_VALUE) return true
    }
  }
  return false
}

function rewriteHead(head, port) {
  const text = head.toString('latin1')
  const cut = text.indexOf('\r\n\r\n')
  const lines = text.slice(0, cut).split('\r\n')
  const requestLine = lines[0]
  const authority = `127.0.0.1:${port}`
  const cookie = cookieFor(authority)

  const out = []
  let sawCookie = false
  let upgrade = false

  for (const line of lines.slice(1)) {
    if (line === '') continue
    const at = line.indexOf(':')
    if (at === -1) continue
    const name = line.slice(0, at)
    const value = line.slice(at + 1).trim()
    const lower = name.toLowerCase()

    if (lower === 'host') { out.push(`Host: ${authority}`); continue }
    if (lower === 'origin') { out.push(`Origin: http://${authority}`); continue }
    if (lower === 'cookie') {
      const kept = value.split(';').map((s) => s.trim())
        .filter((s) => s !== '' && !s.startsWith('dsh-auth-'))
      kept.push(cookie)
      out.push(`Cookie: ${kept.join('; ')}`)
      sawCookie = true
      continue
    }
    if (lower === 'upgrade') { upgrade = true; out.push(line); continue }
    // Dropping the client's Connection header is deliberate: one request per upstream
    // connection is what keeps every request rewritten. A reused keep-alive socket would
    // carry later requests with the LAN Host header and the fence answers "forbidden".
    if (lower === 'connection') { continue }
    out.push(line)
  }

  if (!sawCookie) out.push(`Cookie: ${cookie}`)
  out.push(upgrade ? 'Connection: Upgrade' : 'Connection: close')
  return Buffer.from(`${requestLine}\r\n${out.join('\r\n')}\r\n\r\n`, 'latin1')
}

createServer((client) => {
  let buf = Buffer.alloc(0)
  let done = false
  client.on('error', () => { })

  const onData = (chunk) => {
    if (done) return
    buf = Buffer.concat([buf, chunk])
    const idx = buf.indexOf('\r\n\r\n')
    if (idx === -1) {
      if (buf.length > 128 * 1024) client.destroy()
      return
    }
    done = true
    client.removeListener('data', onData)

    const head = buf.subarray(0, idx + 4)
    const rest = buf.subarray(idx + 4)
    const headText = head.toString('latin1')
    const requestLine = headText.slice(0, headText.indexOf('\r\n'))
    const targetPath = (requestLine.split(' ')[1] ?? '/').split('?')[0]
    const headers = headText.slice(0, headText.indexOf('\r\n\r\n')).split('\r\n').slice(1)
      .filter((line) => line !== '')
      .map((line) => { const at = line.indexOf(':'); return [line.slice(0, at), line.slice(at + 1).trim()] })

    if (targetPath === GATE_PATH) {
      client.end(`HTTP/1.1 302 Found\r\nLocation: /\r\nSet-Cookie: ${GATE_COOKIE}=${GATE_VALUE}; `
        + `Path=/; Max-Age=2592000; HttpOnly; SameSite=Lax\r\nContent-Length: 0\r\n`
        + `Connection: close\r\nCache-Control: no-store\r\n\r\n`)
      log(`gate ${requestLine} -> cookie issued`)
      return
    }
    if (!gated(headers)) {
      const page = '<!doctype html><meta charset="utf-8"><title>DeepSeek Harness</title>'
        + '<body style="font:15px/1.6 system-ui;padding:28px"><h3>entry link required</h3>'
        + '<p>Open the entry URL that ends in <code>/e/PIN</code>.</p>'
      client.end(`HTTP/1.1 401 Unauthorized\r\nContent-Type: text/html; charset=utf-8\r\n`
        + `Content-Length: ${Buffer.byteLength(page)}\r\nConnection: close\r\n`
        + `Cache-Control: no-store\r\n\r\n${page}`)
      log(`gate ${requestLine} -> 401`)
      return
    }

    const port = desktopPort()
    if (port === null) {
      client.end('HTTP/1.1 503 Service Unavailable\r\nContent-Type: text/plain\r\n'
        + 'Content-Length: 44\r\nConnection: close\r\n\r\ndesktop harness host not running; start the Desktop app')
      log('503 no desktop port')
      return
    }

    let rewritten
    try { rewritten = rewriteHead(head, port) }
    catch (error) {
      client.end('HTTP/1.1 500 Internal Server Error\r\nContent-Length: 0\r\nConnection: close\r\n\r\n')
      log(`500 ${error.message}`)
      return
    }

    const firstLine = rewritten.toString('latin1').split('\r\n')[0]
    const upstream = connect(port, '127.0.0.1', () => {
      upstream.write(rewritten)
      if (rest.length > 0) upstream.write(rest)
      upstream.pipe(client)
      client.pipe(upstream)
      log(`-> ${port} ${firstLine}`)
    })
    upstream.on('error', (error) => {
      log(`upstream error ${error.message}`)
      try { client.destroy() } catch { }
    })
    client.on('close', () => { try { upstream.destroy() } catch { } })
  }

  client.on('data', onData)
}).listen(listenPort, listenHost, () => {
  console.log(`lan bridge: http://${listenHost}:${listenPort}/e/${pin} -> 127.0.0.1:<desktop host port>`)
})
'@
Set-Content -Path (Join-Path $OutDir 'lan-bridge.mjs') -Value $bridge -Encoding utf8

