$entry = @'
// phone-entry.mjs - PIN-gated redirect to the separate harness host's tokenized URL.
//   GET /e/<PIN>  -> 302 to the host's current ?token=... URL. That URL mints the
//                    official 30-day cookie; the token itself is re-read from the host
//                    log on every request, so the QR code survives host restarts.
//   anything else -> 404. This is deliberately NOT an open redirect: without the PIN
//                    it would hand the credential to anyone on the LAN.
// Env: DSH_PHONE_HOST, DSH_PHONE_PORT, DSH_PHONE_PIN, DSH_PHONE_LOG, DSH_PHONE_LOGDIR
import { createServer } from 'node:http'
import { readFileSync, appendFileSync } from 'node:fs'
import { join } from 'node:path'

const host = process.env.DSH_PHONE_HOST ?? '127.0.0.1'
const port = Number(process.env.DSH_PHONE_PORT ?? 64601)
const pin = process.env.DSH_PHONE_PIN ?? ''
const hostLog = process.env.DSH_PHONE_LOG ?? ''
const logDir = process.env.DSH_PHONE_LOGDIR ?? '.'
const entryPath = `/e/${pin}`

if (!pin) {
  console.error('phone-entry: DSH_PHONE_PIN is required')
  process.exit(2)
}

function currentTarget() {
  try {
    const text = readFileSync(hostLog, 'utf8')
    const matches = [...text.matchAll(/dsh web: (http\S+)/g)]
    return matches.length ? matches[matches.length - 1][1] : null
  } catch { return null }
}

function log(line) {
  try { appendFileSync(join(logDir, 'phone-entry.log'), `${new Date().toISOString()} ${line}\n`) } catch { }
}

createServer((req, res) => {
  const ip = (req.socket.remoteAddress ?? '').replace(/^::ffff:/u, '')
  const url = req.url ?? '/'

  if (url.startsWith('/healthz')) {
    res.writeHead(200, { 'content-type': 'text/plain', 'cache-control': 'no-store' })
    res.end('ok')
    return
  }

  if (url === entryPath || url === `${entryPath}/`) {
    const target = currentTarget()
    if (!target) {
      res.writeHead(503, { 'content-type': 'text/plain; charset=utf-8', 'cache-control': 'no-store' })
      res.end('harness host is not running')
      log(`${ip} ${url} 503`)
      return
    }
    res.writeHead(302, {
      Location: target,
      'content-type': 'text/html; charset=utf-8',
      'cache-control': 'no-store',
      'referrer-policy': 'no-referrer'
    })
    res.end(`<!doctype html><meta charset="utf-8"><meta name="referrer" content="no-referrer">`
      + `<body style="font:16px/1.7 system-ui;padding:28px"><p>entering... `
      + `<a href="${target}" rel="noreferrer">open manually</a></p>`)
    log(`${ip} ${url} 302 -> ${target}`)
    return
  }

  res.writeHead(404, { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' })
  res.end('<!doctype html><meta charset="utf-8"><body style="font:15px/1.6 system-ui;padding:28px">'
    + '<h3>404</h3><p>This port only accepts the entry path with the PIN.</p>')
  log(`${ip} ${url} 404`)
}).listen(port, host, () => {
  console.log(`phone entry: http://${host}:${port}${entryPath}`)
})
'@
Set-Content -Path (Join-Path $OutDir 'phone-entry.mjs') -Value $entry -Encoding utf8

