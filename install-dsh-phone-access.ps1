$watchdog = @'
# lan-watchdog.ps1 - keep the three listeners alive on whatever address this machine has.
# Start it from Task Scheduler, never as a child of the Desktop app: the app clears its
# whole process tree on restart, which takes any child supervisor with it.
param([string]$OutDir = $PSScriptRoot, [int]$IntervalSeconds = 15)
. (Join-Path $OutDir 'config.ps1')

$ErrorActionPreference = 'SilentlyContinue'
$logPath = Join-Path $OutDir 'lan-watchdog.log'

function Log([string]$text) {
  try {
    Add-Content -Path $logPath -Value "$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') $text" -Encoding utf8
    $all = Get-Content $logPath
    if ($all.Count -gt 400) { $all[-200..-1] | Set-Content $logPath -Encoding utf8 }
  } catch { }
}

function LanAddress {
    $route = Get-NetRoute -DestinationPrefix '0.0.0.0/0' | Sort-Object RouteMetric, InterfaceMetric | Select-Object -First 1
    if ($route) {
        $ip = Get-NetIPAddress -InterfaceIndex $route.InterfaceIndex -AddressFamily IPv4 |
            Where-Object { $_.IPAddress -ne '127.0.0.1' -and $_.IPAddress -notlike '169.254*' } | Select-Object -First 1
        if ($ip) { return $ip.IPAddress }
    }
    $any = Get-NetIPAddress -AddressFamily IPv4 | Where-Object { $_.IPAddress -ne '127.0.0.1' -and $_.IPAddress -notlike '169.254*' } | Select-Object -First 1
    if ($any) { return $any.IPAddress }
    return ''
}

# A listener bound to an address this machine no longer owns still shows as LISTEN but is
# unreachable - it has to be treated as down, not as healthy.
function BoundTo([int]$port, [string]$address) {
    $c = Get-NetTCPConnection -LocalPort $port -State Listen
    if (-not $c) { return $false }
    foreach ($x in $c) { if ($x.LocalAddress -eq $address) { return $true } }
    return $false
}

function StopStale([int]$port, [string]$address) {
    foreach ($x in (Get-NetTCPConnection -LocalPort $port -State Listen)) {
        if ($x.LocalAddress -ne $address) {
            Log "$port bound to stale $($x.LocalAddress) -> killing $($x.OwningProcess)"
            Stop-Process -Id $x.OwningProcess -Force
        }
    }
}

function StartPart([string]$label, [scriptblock]$body, [int]$port, [int]$waitSeconds) {
    Log "$label :$port down -> starting"
    try { & $body | Out-Null } catch { Log "$label start threw: $($_.Exception.Message)" }
    for ($i = 0; $i -lt ($waitSeconds * 2); $i++) {
        Start-Sleep -Milliseconds 500
        if (Get-NetTCPConnection -LocalPort $port -State Listen) { break }
    }
    if (Get-NetTCPConnection -LocalPort $port -State Listen) { Log "$label :$port up" }
    else { Log "$label start FAILED" }
}

