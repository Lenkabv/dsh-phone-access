# --------------------------------------------------------------------------- helpers

function Test-Admin {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    return ([Security.Principal.WindowsPrincipal]$id).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Resolve-LanAddress {
    # The address of the interface that owns the default route: the one a phone can reach.
    $route = Get-NetRoute -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue |
        Sort-Object RouteMetric, InterfaceMetric | Select-Object -First 1
    if ($route) {
        $ip = Get-NetIPAddress -InterfaceIndex $route.InterfaceIndex -AddressFamily IPv4 -ErrorAction SilentlyContinue |
            Where-Object { $_.IPAddress -ne '127.0.0.1' -and $_.IPAddress -notlike '169.254*' } | Select-Object -First 1
        if ($ip) { return $ip.IPAddress }
    }
    $any = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object { $_.IPAddress -ne '127.0.0.1' -and $_.IPAddress -notlike '169.254*' } | Select-Object -First 1
    if ($any) { return $any.IPAddress }
    throw 'no non-loopback IPv4 address found - connect to WiFi/Ethernet first'
}

function New-Pin {
    $alphabet = '23456789abcdefghjkmnpqrstuvwxyz'   # no 0/1/i/l/o: typable and unambiguous
    -join (1..8 | ForEach-Object { $alphabet[(Get-Random -Maximum $alphabet.Length)] })
}

function Find-DshCliEntry([string]$root) {
    $candidates = @(
        (Join-Path $root 'resources\app\dsh\node_modules\@deepseek-ai\dsh-desktop-host\lib\cli.js'),
        (Join-Path $root 'resources\app\app.asar.unpacked\dsh\node_modules\@deepseek-ai\dsh-desktop-host\lib\cli.js')
    )
    foreach ($c in $candidates) { if (Test-Path $c) { return $c } }
    throw "cannot find the dsh CLI entry under $root - pass -DshRoot pointing at the install directory"
}

