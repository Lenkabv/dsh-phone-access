$startBridge = @'
# lan-bridge.ps1 - start the reverse proxy to the Desktop app's own harness host.
param([string]$HostAddress, [int]$Port, [string]$OutDir = $PSScriptRoot)
. (Join-Path $OutDir 'config.ps1')
if (-not $HostAddress) { $HostAddress = $LanAddress }
if (-not $Port) { $Port = $BridgePort }

# Where is the Desktop app's harness host listening? Its child process owns a loopback
# port and its command line names dsh-desktop-host\lib\index.js (or cli.js).
$portFile = Join-Path $OutDir 'desktop-host.port'
$found = $null
foreach ($c in (Get-NetTCPConnection -State Listen -ErrorAction SilentlyContinue | Where-Object { $_.LocalAddress -in @('127.0.0.1', '::1') })) {
  $p = Get-CimInstance Win32_Process -Filter "ProcessId=$($c.OwningProcess)" -ErrorAction SilentlyContinue
  if ($p.CommandLine -and $p.CommandLine -match 'dsh-desktop-host[\\/]lib[\\/](cli|index)\.js') { $found = $c.LocalPort; break }
}
if (-not $found) {
  Remove-Item $portFile -ErrorAction SilentlyContinue
  throw 'desktop harness host not found - is the DeepSeek Harness Desktop app running?'
}
Set-Content -Path $portFile -Value $found -Encoding ascii -NoNewline

$busy = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue
foreach ($b in $busy) { Stop-Process -Id $b.OwningProcess -Force -ErrorAction SilentlyContinue }
if ($busy) { Start-Sleep -Seconds 1 }

$env:ELECTRON_RUN_AS_NODE = '1'
$env:DSH_BRIDGE_HOST = $HostAddress
$env:DSH_BRIDGE_PORT = "$Port"
$env:DSH_BRIDGE_DIR  = $OutDir
$env:DSH_BRIDGE_PIN  = $PhonePin
Start-Process -FilePath $DshExe -ArgumentList ('--expose-internals "{0}"' -f (Join-Path $OutDir 'lan-bridge.mjs')) `
  -WindowStyle Hidden -WorkingDirectory $OutDir | Out-Null

for ($i = 0; $i -lt 20; $i++) {
  Start-Sleep -Milliseconds 500
  if (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue) { break }
}
Write-Output "http://${HostAddress}:$Port/e/$PhonePin -> 127.0.0.1:$found"
'@
Set-Content -Path (Join-Path $OutDir 'lan-bridge.ps1') -Value $startBridge -Encoding utf8

