$startHost = @'
# start-lan-web.ps1 - run a separate `dsh web` host bound to the LAN address.
param([string]$HostAddress, [int]$Port, [string]$OutDir = $PSScriptRoot)
. (Join-Path $OutDir 'config.ps1')
if (-not $HostAddress) { $HostAddress = $LanAddress }
if (-not $Port) { $Port = $HostPort }

$logOut = Join-Path $OutDir 'lan-web.out.log'
$logErr = Join-Path $OutDir 'lan-web.err.log'

$busy = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue
$onOurs = @($busy | Where-Object { $_.LocalAddress -eq $HostAddress })
$stale  = @($busy | Where-Object { $_.LocalAddress -ne $HostAddress })
foreach ($b in $stale) { Stop-Process -Id $b.OwningProcess -Force -ErrorAction SilentlyContinue }
if ($stale.Count -gt 0) { Start-Sleep -Seconds 2 }

if ($onOurs.Count -eq 0) {
  Remove-Item $logOut, $logErr -ErrorAction SilentlyContinue
  $env:ELECTRON_RUN_AS_NODE = '1'
