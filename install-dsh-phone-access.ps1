#Requires -Version 5.1
<#
.SYNOPSIS
    Give a phone browser access to the DeepSeek Harness Desktop app on the same LAN.

.DESCRIPTION
    Writes a small set of helper processes next to your user profile and (optionally)
    registers them with Task Scheduler and opens the firewall. Nothing inside the
    DeepSeek Harness installation is modified.

    Two independent entry points are produced:

      64600/64601  a separate `dsh web` process  -> its own sessions, token auth
      64602        a reverse proxy to the Desktop app's own harness process
                   -> the phone and the desktop share the same live sessions

    64602 exists because a second harness process cannot open a session the Desktop
    app already holds ("error.sessionInUse"), so the only way to share a session is
    to talk to the Desktop app's process itself.

.NOTES
    Written against DeepSeek Harness 0.2.1-rc.3 (Windows, packaged desktop build).
    The proxy depends on three internals; see README.md ("Version coupling").
    Keep the produced directory private: it can drive your machine.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\install-dsh-phone-access.ps1 -InstallTask
#>
param(
    [string]$OutDir = (Join-Path $env:USERPROFILE 'Documents\dsh-phone-access'),
    [string]$DshRoot = (Join-Path $env:LOCALAPPDATA 'Programs\DeepSeek Harness'),
    [string]$LanAddress,
    [string]$Pin,
    [int]$HostPort = 64600,
    [int]$EntryPort = 64601,
    [int]$BridgePort = 64602,
    [switch]$InstallTask,
    [switch]$SkipStart
)

