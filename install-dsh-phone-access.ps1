        try { & (Join-Path $OutDir 'lan-bridge.ps1') -HostAddress $addr -Port $BridgePort -OutDir $OutDir | Out-Null } catch { }
        $after = if (Test-Path $portFile) { (Get-Content $portFile -Raw).Trim() } else { '' }
