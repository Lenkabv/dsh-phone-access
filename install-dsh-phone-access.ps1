    -RedirectStandardError $logErr -WindowStyle Hidden -WorkingDirectory $OutDir | Out-Null
}

# wait for the "dsh web: <url>" line, then publish it
for ($i = 0; $i -lt 60; $i++) {
  Start-Sleep -Seconds 2
  $m = Select-String -Path $logOut -Pattern 'dsh web: (http\S+)' -ErrorAction SilentlyContinue | Select-Object -Last 1
  if ($m) { Write-Output $m.Matches[0].Groups[1].Value; exit 0 }
}
throw "host did not print a URL; see $logErr"
'@
Set-Content -Path (Join-Path $OutDir 'start-lan-web.ps1') -Value $startHost -Encoding utf8

